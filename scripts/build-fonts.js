'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { publishBuildOutputs } = require('./build-output');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'public', 'fonts');

// The CSP only allows same-origin fonts, so UI fonts are self-hosted.
// Inter carries Latin and digits; Noto Sans SC fills in CJK behind it.
// Fontsource splits each weight into unicode-range subsets; browsers download
// only the subsets a page actually renders.
//
// SemiBold is the heaviest cut shipped: it is declared for 600–1000 so the
// UI's many 650–800 weights render as one calm SemiBold instead of a heavy
// Bold, without the browser synthesizing faux bold.
const FAMILIES = [
  { pkg: 'inter', weights: { 400: '400', 500: '500', 600: '600 1000' } },
  { pkg: 'noto-sans-sc', weights: { 400: '400', 500: '500', 600: '600 1000' } },
  { pkg: 'noto-serif-sc', weights: { 600: '600 1000' } }
];

const outputs = [];
const sheets = ['/* Generated by npm run build. Inter, Noto Sans SC, Noto Serif SC (OFL-1.1) via Fontsource. */'];

for (const { pkg, weights } of FAMILIES) {
  const dir = path.dirname(require.resolve(`@fontsource/${pkg}/package.json`));
  for (const [weight, range] of Object.entries(weights)) {
    const css = fs.readFileSync(path.join(dir, `${weight}.css`), 'utf8')
      // woff2 covers every browser this app supports; drop the .woff fallback.
      .replace(/,\s*url\([^)]+\.woff\) format\('woff'\)/g, '')
      .replace(/font-weight: \d+;/g, `font-weight: ${range};`)
      .replace(/url\(\.\/files\/([^)]+\.woff2)\)/g, (_, file) => {
        outputs.push({ path: path.join(OUT_DIR, file), contents: fs.readFileSync(path.join(dir, 'files', file)) });
        return `url(${file})`;
      });
    sheets.push(css.trim());
  }
}

outputs.push({ path: path.join(OUT_DIR, 'inter.LICENSE.txt'),
  contents: fs.readFileSync(require.resolve('@fontsource/inter/LICENSE')) });
outputs.push({ path: path.join(OUT_DIR, 'noto-sc.LICENSE.txt'),
  contents: fs.readFileSync(require.resolve('@fontsource/noto-sans-sc/LICENSE')) });
outputs.push({ path: path.join(OUT_DIR, 'noto-sc.css'), contents: Buffer.from(sheets.join('\n\n') + '\n') });

publishBuildOutputs(outputs, { root: ROOT }).then(() => {
  // Drop subsets of weights that are no longer shipped.
  const kept = new Set(outputs.map((output) => path.basename(output.path)));
  for (const name of fs.readdirSync(OUT_DIR)) {
    if (!kept.has(name)) fs.rmSync(path.join(OUT_DIR, name));
  }
}).catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
