'use strict';

const path = require('node:path');
const esbuild = require('esbuild');
const { publishBuildOutputs } = require('./build-output');

const root = path.resolve(__dirname, '..');
const shared = { bundle: true, minify: true, target: 'es2022', logLevel: 'warning', write: false };

async function buildScript(directory, filename, globalName, entry = 'index.js') {
  return esbuild.build({
    ...shared,
    entryPoints: [path.join(root, 'frontend', directory, entry)],
    outfile: path.join(root, 'public', filename),
    format: 'iife',
    external: ['fflate'],
    ...(globalName ? { globalName } : {}),
    banner: { js: `// Generated by npm run build:frontend. Edit frontend/${directory} instead.` },
    ...(globalName
      ? { footer: { js: `if (typeof module === 'object' && module.exports) module.exports = ${globalName};` } }
      : {}),
    plugins: [
      {
        name: 'public-adapters',
        setup(build) {
          // Browser adapters are loaded by index.html and shared with Workers.
          // Node consumers keep the same sibling require paths in the built file.
          build.onResolve({ filter: /public\/[^/]+\.js$/ }, (args) => ({
            path: './' + path.basename(args.path),
            external: true
          }));
        }
      }
    ]
  });
}

// Studio themes = overrides derived from the classic CSS + hand-written theme rules.
async function buildThemes(classicCss) {
  const fs = require('node:fs/promises');
  const { generateThemeOverrides } = require('./theme-overrides');
  const extra = await Promise.all(['side-tools.css', 'connector.css'].map((name) =>
    fs.readFile(path.join(root, 'public', name), 'utf8').catch(() => '')));
  const derived = generateThemeOverrides([Buffer.from(classicCss).toString('utf8'), ...extra]);
  const themed = await esbuild.build({
    ...shared,
    entryPoints: [path.join(root, 'frontend/styles/themes/index.css')],
    outfile: path.join(root, 'public/themes.css')
  });
  const minifiedDerived = await esbuild.transform(derived, { loader: 'css', minify: true, target: 'es2022' });
  const banner = '/* Generated by npm run build:frontend. Edit frontend/styles/themes or scripts/theme-overrides.js instead. */\n';
  const contents = Buffer.from(banner + minifiedDerived.code + Buffer.from(themed.outputFiles[0].contents).toString('utf8'), 'utf8');
  return { outputFiles: [{ path: path.join(root, 'public/themes.css'), contents }] };
}

// Kando's pie-menu renderer (MIT), vendored under frontend/kando-menu and loaded on demand.
async function buildKandoMenu() {
  return esbuild.build({
    ...shared,
    entryPoints: [path.join(root, 'frontend/kando-menu/index.ts')],
    outfile: path.join(root, 'public/kando-menu.js'),
    format: 'esm',
    alias: { events: path.join(root, 'frontend/kando-menu/shims/events.js') },
    define: { cIsWindows: 'false', cIsMac: 'false' },
    legalComments: 'none',
    banner: { js: '/*! Museboard radial menu, built from Kando (https://github.com/kando-menu/kando), MIT License, Copyright (c) Simon Schneegans and Kando contributors. Edit frontend/kando-menu instead. */' }
  });
}

async function main() {
  const results = [];
  results.push(await buildScript('notebook', 'notes-workspace.js', 'MuseNotebook', 'app.js'));
  results.push(await buildScript('planning', 'planning.js', null, 'index.js'));
  results.push(await buildScript('formula', 'sheet-formula.js', 'SheetFormula'));
  results.push(await buildScript('sheet-core', 'sheet-core.js', 'SheetCore'));
  results.push(await buildScript('sheet-view', 'sheet-view.js', 'SheetView'));
  results.push(await buildScript('sheet-editor', 'sheet-editor.js', 'SheetEditor'));
  results.push(await buildScript('sheet-xlsx', 'sheet-xlsx.js', 'SheetXlsx'));
  results.push(await buildScript('account', 'account.js', null, 'bootstrap.js'));
  results.push(await buildScript('brush', 'brush-engine.js', null, 'bootstrap.js'));
  results.push(await buildKandoMenu());
  results.push(await esbuild.build({
    ...shared,
    entryPoints: [path.join(root, 'frontend/styles/index.css')],
    outfile: path.join(root, 'public/styles.css'),
    external: ['backgrounds/*', 'text-borders/*', 'section-frames/*', 'section-backdrops/*'],
    banner: { css: '/* Generated by npm run build:frontend. Edit frontend/styles instead. */' }
  }));
  results.push(await buildThemes(results[results.length - 1].outputFiles[0].contents));
  await publishBuildOutputs(results.flatMap((result) => result.outputFiles), { root });
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
