let floatingToolbarMoveAnimation = null;

let floatingToolbarDrag = null;

function onFloatingToolbarDragStart(event) {
  // A new pointer gesture cannot be the click generated by the previous drag.
  formatControlsRuntime.floatingToolbarSuppressedPointerId = null;
  const bar = els.floatingFormatBar;
  if (!bar || bar.hidden || event.button !== 0 || floatingToolbarDrag) return;
  if (event.target.closest('.floating-format-more, .floating-color-palette, .floating-select-menu, input, select'))
    return;
  floatingToolbarDrag = {
    pointerId: event.pointerId,
    startX: event.clientX,
    startY: event.clientY,
    startLeft: 0,
    startTop: 0,
    active: false,
    targetId: state.floatingToolbarTargetId
  };
}

function onFloatingToolbarDragMove(event) {
  const drag = floatingToolbarDrag;
  if (!drag || drag.pointerId !== event.pointerId) return;
  const bar = els.floatingFormatBar;
  if (!drag.active) {
    if (Math.hypot(event.clientX - drag.startX, event.clientY - drag.startY) < 5) return;
    const rect = bar.getBoundingClientRect();
    drag.startLeft = rect.left;
    drag.startTop = rect.top;
    drag.active = true;
    drag.snapTargets = collectFloatingToolbarSnapTargets();
    bar.style.setProperty('--floating-toolbar-x', `${rect.left}px`);
    bar.style.setProperty('--floating-toolbar-y', `${rect.top}px`);
    floatingToolbarMoveAnimation?.cancel?.();
    floatingToolbarMoveAnimation = null;
    bar.classList.add('is-dragging');
    bar.setPointerCapture(event.pointerId);
  }
  event.preventDefault();
  floatingToolbarPositionRuntime.floatingToolbarManualPosition = {
    targetId: drag.targetId,
    x: drag.startLeft + event.clientX - drag.startX,
    y: drag.startTop + event.clientY - drag.startY
  };
  scheduleFloatingToolbarPosition();
}

function onFloatingToolbarDragEnd(event) {
  const drag = floatingToolbarDrag;
  if (!drag || drag.pointerId !== event.pointerId) return;
  floatingToolbarDrag = null;
  const bar = els.floatingFormatBar;
  bar?.classList.remove('is-dragging');
  if (bar?.hasPointerCapture?.(event.pointerId)) bar.releasePointerCapture(event.pointerId);
  if (drag.active) {
    if (floatingToolbarPositionRuntime.floatingToolbarManualPosition?.targetId === drag.targetId) {
      floatingToolbarPositionRuntime.floatingToolbarManualPosition.anchor = captureFloatingToolbarAnchorSnapshot();
    }
    formatControlsRuntime.floatingToolbarSuppressedPointerId = event.pointerId;
    scheduleFloatingToolbarPosition();
  }
}

function captureFloatingToolbarAnchorSnapshot() {
  const item = getSelectedOrEditingItem();
  const node = item && resolveFloatingToolbarAnchorNode(item);
  if (!node) return null;
  const itemRect = node.getBoundingClientRect();
  return floatingToolbarAnchorValues(itemRect, getEditingCaretScreenRect(), floatingToolbarSafeRect());
}

function collectFloatingToolbarSnapTargets() {
  const safe = floatingToolbarSafeRect();
  const targets = [];
  for (const [root, selector, kind] of [
    [els.itemsLayer, '.board-item', 'item'],
    [els.sectionLayer, '.section-frame:not(.section-draft):not(.is-hidden)', 'section']
  ]) {
    root?.querySelectorAll(selector).forEach((node) => {
      if (!node.getClientRects().length) return;
      const rect = node.getBoundingClientRect();
      if (
        rect.width < 1 ||
        rect.height < 1 ||
        rect.right < safe.left ||
        rect.left > safe.right ||
        rect.bottom < safe.top ||
        rect.top > safe.bottom
      )
        return;
      targets.push({
        left: rect.left,
        right: rect.right,
        top: rect.top,
        bottom: rect.bottom,
        key: `${kind}:${node.dataset.itemId || node.dataset.sectionId || targets.length}`
      });
    });
  }
  return targets;
}

function floatingToolbarSafeRect() {
  const viewport = els.viewport?.getBoundingClientRect() || { left: 0, top: 0, right: innerWidth, bottom: innerHeight };
  const visual = window.visualViewport;
  const left = visual?.offsetLeft || 0, top = visual?.offsetTop || 0;
  return {
    left: Math.max(left + 12, viewport.left + 12),
    top: Math.max(top + 12, viewport.top + 12),
    right: Math.min(left + (visual?.width || innerWidth) - 12, viewport.right - 12),
    bottom: Math.min(top + (visual?.height || innerHeight) - 12, viewport.bottom - 12)
  };
}

function getEditingCaretScreenRect() {
  const textContext = getEditingTextContext();
  const mindContext = textContext ? null : getEditingMindNodeContext();
  const editable = textContext?.editable || mindContext?.editable;
  if (!editable) return null;
  const selection = window.getSelection();
  let range = null;
  if (selectionBelongsToEditable(selection, editable)) {
    range = cloneSelectionFocusRange(selection);
  }
  if (!range) {
    const savedRanges =
      textContext?.item.id === state.textSelection?.itemId
        ? [state.textSelection?.caretRange, state.textSelection?.range]
        : [mindContext?.editing.caretRange];
    for (const saved of savedRanges) {
      if (!saved || !editable.contains(saved.startContainer)) continue;
      try {
        range = saved.cloneRange();
      } catch {}
      if (range) break;
    }
  }
  if (range) {
    let rect = null;
    try {
      range.collapse(true);
      rect = range.getBoundingClientRect();
    } catch {}
    if (rect && Number.isFinite(rect.left) && (rect.width || rect.height)) {
      return {
        left: rect.left,
        right: rect.right || rect.left + 1,
        top: rect.top,
        bottom: rect.bottom || rect.top + 18,
        width: Math.max(1, rect.width),
        height: Math.max(18, rect.height)
      };
    }
  }
  return null;
}

function caretToolbarTextOverlap(above, below, editable) {
  if (!editable) return { above: false, below: false };
  const bounds = editable.getBoundingClientRect();
  const checkAbove = rectOverlapArea(above, bounds) > 0;
  const checkBelow = rectOverlapArea(below, bounds) > 0;
  if (!checkAbove && !checkBelow) return { above: false, below: false };
  const root = editable.closest('.board-item') || editable;
  if (root !== floatingToolbarPositionRuntime.floatingToolbarTextOverlapRoot) {
    floatingToolbarPositionRuntime.floatingToolbarTextOverlapObserver?.disconnect();
    floatingToolbarPositionRuntime.floatingToolbarTextOverlapRoot = root;
    floatingToolbarPositionRuntime.floatingToolbarTextOverlapCache = null;
    floatingToolbarPositionRuntime.floatingToolbarTextOverlapObserver = new MutationObserver(() => {
      floatingToolbarPositionRuntime.floatingToolbarTextOverlapCache = null;
    });
    floatingToolbarPositionRuntime.floatingToolbarTextOverlapObserver.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true
    });
  }
  // Mutation callbacks run later; takeRecords also catches edits in this task.
  if (floatingToolbarPositionRuntime.floatingToolbarTextOverlapObserver.takeRecords().length)
    floatingToolbarPositionRuntime.floatingToolbarTextOverlapCache = null;
  const geometry = [
    above.left,
    above.top,
    above.right,
    above.bottom,
    below.left,
    below.top,
    below.right,
    below.bottom,
    bounds.left,
    bounds.top,
    bounds.right,
    bounds.bottom,
    editable.scrollLeft,
    editable.scrollTop
  ];
  const cached = floatingToolbarPositionRuntime.floatingToolbarTextOverlapCache;
  if (cached?.editable === editable && geometry.every((value, index) => value === cached.geometry[index]))
    return cached.result;
  const overlapsVisibleText = (candidate, rect) => {
    const left = Math.max(candidate.left, rect.left, bounds.left);
    const right = Math.min(candidate.right, rect.right, bounds.right);
    const top = Math.max(candidate.top, rect.top, bounds.top);
    const bottom = Math.min(candidate.bottom, rect.bottom, bounds.bottom);
    // Ignore fractional edge contact so subpixel layout does not flip the side.
    return right - left > 2 && bottom - top > 2;
  };
  let aboveCovered = false;
  let belowCovered = false;
  const walker = document.createTreeWalker(editable, NodeFilter.SHOW_TEXT);
  const range = document.createRange();
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.textContent?.replace(/\u200b/g, '').trim()) continue;
    range.selectNodeContents(node);
    for (const rect of range.getClientRects()) {
      if (checkAbove && !aboveCovered && overlapsVisibleText(above, rect)) aboveCovered = true;
      if (checkBelow && !belowCovered && overlapsVisibleText(below, rect)) belowCovered = true;
      if ((!checkAbove || aboveCovered) && (!checkBelow || belowCovered)) {
        const result = { above: aboveCovered, below: belowCovered };
        floatingToolbarPositionRuntime.floatingToolbarTextOverlapCache = { editable, geometry, result };
        return result;
      }
    }
  }
  const result = { above: aboveCovered, below: belowCovered };
  floatingToolbarPositionRuntime.floatingToolbarTextOverlapCache = { editable, geometry, result };
  return result;
}

function resolveFloatingToolbarAnchorNode(item) {
  const mindContext = item.type === 'mindmap' ? getEditingMindNodeContext() : null;
  return mindContext?.element || document.querySelector(`.board-item[data-item-id="${cssEscape(item.id)}"]`);
}

function positionFloatingToolbar() {
  const bar = els.floatingFormatBar;
  const item = getSelectedOrEditingItem();
  if (!bar || bar.hidden || !floatingToolbarUsesTarget(item)) return;
  const targetNode = resolveFloatingToolbarAnchorNode(item);
  if (!targetNode) return;
  const itemRect = targetNode.getBoundingClientRect();
  // The toolbar is viewport UI. Keeping it at a fixed CSS-pixel size prevents
  // camera zoom from repeatedly changing its measured bounds and eliminates
  // the feedback loop that previously caused visible shake.
  bar.style.setProperty('--floating-toolbar-scale', '1');
  const barRect = bar.getBoundingClientRect();
  if (!barRect.width || !barRect.height) return;
  const safe = floatingToolbarSafeRect();
  const rawCaret = getEditingCaretScreenRect();
  if (
    floatingToolbarPositionRuntime.floatingToolbarManualPosition?.targetId === state.floatingToolbarTargetId &&
    !floatingToolbarDrag?.active &&
    floatingToolbarAnchorChanged(
      floatingToolbarPositionRuntime.floatingToolbarManualPosition.anchor,
      itemRect,
      rawCaret,
      safe
    )
  ) {
    floatingToolbarPositionRuntime.floatingToolbarManualPosition = null;
    floatingToolbarPositionRuntime.floatingToolbarCommittedCaret = null;
  }
  let caret = rawCaret;
  const rawFocusPoint = rawCaret
    ? { x: (rawCaret.left + rawCaret.right) / 2, y: (rawCaret.top + rawCaret.bottom) / 2 }
    : { x: itemRect.left + itemRect.width / 2, y: itemRect.top + itemRect.height / 2 };
  // A viewport-relative reach gives the caret a consistent, usable distance
  // from the toolbar without tying relocation to how far the caret has moved.
  const comfortableReach = clamp(Math.min(safe.right - safe.left, safe.bottom - safe.top) * 0.2, 88, 150);
  const reanchorReach = comfortableReach + 28;
  const fitsSafe = (candidate) =>
    candidate.left >= safe.left &&
    candidate.right <= safe.right &&
    candidate.top >= safe.top &&
    candidate.bottom <= safe.bottom;
  const edgeVisible = (candidate) => {
    const horizontalOverlap = itemRect.right > safe.left && itemRect.left < safe.right;
    const verticalOverlap = itemRect.bottom > safe.top && itemRect.top < safe.bottom;
    if (candidate.key === 'top') return horizontalOverlap && itemRect.top >= safe.top && itemRect.top <= safe.bottom;
    if (candidate.key === 'bottom')
      return horizontalOverlap && itemRect.bottom >= safe.top && itemRect.bottom <= safe.bottom;
    if (candidate.key === 'left') return verticalOverlap && itemRect.left >= safe.left && itemRect.left <= safe.right;
    return verticalOverlap && itemRect.right >= safe.left && itemRect.right <= safe.right;
  };
  const borderCandidates = getFloatingToolbarCandidates(itemRect, rawFocusPoint, barRect.width, barRect.height).filter(
    (candidate) => edgeVisible(candidate) && fitsSafe(candidate)
  );
  const borderWithinReach = borderCandidates.some(
    (candidate) => pointDistanceToRect(rawFocusPoint, candidate) <= comfortableReach
  );
  const geometry = [
    itemRect.left,
    itemRect.top,
    itemRect.right,
    itemRect.bottom,
    safe.left,
    safe.top,
    safe.right,
    safe.bottom,
    barRect.width,
    barRect.height
  ];
  const previousCaret = floatingToolbarPositionRuntime.floatingToolbarCommittedCaret;
  const sameGeometry =
    previousCaret?.targetId === state.floatingToolbarTargetId &&
    geometry.every((value, index) => Math.abs(value - previousCaret.geometry[index]) < 0.5);
  const placedX = Number(bar.dataset.positionX);
  const placedY = Number(bar.dataset.positionY);
  const placedRect =
    Number.isFinite(placedX) && Number.isFinite(placedY)
      ? candidateRect(placedX, placedY, barRect.width, barRect.height, 'placed')
      : null;
  const keepPreviousCaret = Boolean(
    rawCaret &&
    sameGeometry &&
    placedRect &&
    fitsSafe(placedRect) &&
    pointDistanceToRect(rawFocusPoint, placedRect) <= reanchorReach &&
    !(bar.dataset.anchorSource === 'caret' && borderWithinReach)
  );
  // Keep the current placement while the caret can still reach the toolbar.
  // The smaller border-entry distance makes switching back to the element edge stable.
  const focusPoint = keepPreviousCaret ? previousCaret.focus : rawFocusPoint;
  if (keepPreviousCaret) {
    const dx = focusPoint.x - rawFocusPoint.x;
    const dy = focusPoint.y - rawFocusPoint.y;
    caret = {
      left: rawCaret.left + dx,
      right: rawCaret.right + dx,
      top: rawCaret.top + dy,
      bottom: rawCaret.bottom + dy
    };
  } else {
    floatingToolbarPositionRuntime.floatingToolbarCommittedCaret = rawCaret
      ? { targetId: state.floatingToolbarTargetId, focus: rawFocusPoint, geometry }
      : null;
  }
  const rawBorderCandidates = getFloatingToolbarCandidates(itemRect, focusPoint, barRect.width, barRect.height);
  const caretVisible = Boolean(
    caret &&
    focusPoint.x >= safe.left &&
    focusPoint.x <= safe.right &&
    focusPoint.y >= safe.top &&
    focusPoint.y <= safe.bottom
  );
  const caretReachThreshold =
    keepPreviousCaret && bar.dataset.anchorSource === 'border' ? reanchorReach : comfortableReach;
  const manualPosition =
    floatingToolbarPositionRuntime.floatingToolbarManualPosition?.targetId === state.floatingToolbarTargetId
      ? floatingToolbarPositionRuntime.floatingToolbarManualPosition
      : null;
  if (manualPosition && floatingToolbarDrag?.active) {
    const snapped = snapFloatingToolbarPosition(
      manualPosition,
      barRect.width,
      barRect.height,
      safe,
      floatingToolbarDrag
    );
    manualPosition.x = snapped.x;
    manualPosition.y = snapped.y;
    manualPosition.snapped = snapped.snapped;
  }
  let source = manualPosition ? 'manual' : 'border';
  let candidates = manualPosition
    ? [
        clampFloatingCandidate(
          candidateRect(manualPosition.x, manualPosition.y, barRect.width, barRect.height, 'manual'),
          safe
        )
      ]
    : rawBorderCandidates.filter((candidate) => edgeVisible(candidate) && fitsSafe(candidate));
  if (!manualPosition && caretVisible && candidates.length) {
    const nearbyBorderCandidates = candidates.filter(
      (candidate) => pointDistanceToRect(focusPoint, candidate) <= caretReachThreshold
    );
    if (nearbyBorderCandidates.length) candidates = nearbyBorderCandidates;
    else candidates = [];
  }
  if (!manualPosition && !candidates.length) {
    source = 'caret';
    const caretCandidates = caret ? getCaretToolbarCandidates(caret, barRect.width, barRect.height) : [];
    let vertical = caretCandidates.filter(
      (candidate) => /caret-(top|bottom)/.test(candidate.key) && fitsSafe(candidate)
    );
    const above = vertical.find((candidate) => candidate.key === 'caret-top');
    const below = vertical.find((candidate) => candidate.key === 'caret-bottom');
    if (above && below) {
      const editable = getEditingTextContext()?.editable || getEditingMindNodeContext()?.editable;
      const overlap = caretToolbarTextOverlap(above, below, editable);
      if (overlap.above) vertical = [overlap.below ? above : below];
    }
    const horizontal = caretCandidates.filter(
      (candidate) => /caret-(left|right)/.test(candidate.key) && fitsSafe(candidate)
    );
    candidates = vertical.length
      ? vertical
      : horizontal.length
        ? horizontal
        : caretCandidates.map((candidate) => clampFloatingCandidate(candidate, safe));
  }
  if (!manualPosition && !candidates.length) {
    candidates = [
      clampFloatingCandidate(
        candidateRect(
          focusPoint.x - barRect.width / 2,
          focusPoint.y - barRect.height - FLOATING_TOOLBAR_CARET_GAP,
          barRect.width,
          barRect.height,
          'caret-top'
        ),
        safe
      )
    ];
  }
  // Only stable application chrome blocks the toolbar. Other canvas elements
  // are intentionally ignored: their rapidly changing rectangles used to make
  // equally scored placements flip on consecutive animation frames.
  const blockers = [];
  for (const surface of [
    els.toolDock,
    document.querySelector('.document-bar'),
    document.querySelector('.canvas-view-controls'),
    els.navigatorPanel
  ]) {
    if (surface && !surface.hidden) blockers.push(surface.getBoundingClientRect());
  }
  const scored = candidates.map((candidate, index) => {
    const collision = blockers.reduce((total, blocker) => total + rectOverlapArea(candidate, blocker, 6), 0);
    const horizontalPenalty = /-(left|right)$|^(left|right)$/.test(candidate.key) ? 25_000 : 0;
    const bottomPenalty = /bottom$/.test(candidate.key) ? 100 : 0;
    const stableBonus = candidate.key === bar.dataset.placement ? -50 : 0;
    return { candidate, score: collision * 8 + horizontalPenalty + bottomPenalty + index + stableBonus };
  });
  scored.sort((a, b) => a.score - b.score);
  const best = scored[0]?.candidate;
  if (!best) return;

  // Measure every open child surface before mutating toolbar position. Reading
  // offset sizes after writing left/top used to force a synchronous relayout on
  // nearly every caret move.
  const morePanel = bar.querySelector('[data-floating-more-panel]');
  const moreVisible = Boolean(morePanel && !morePanel.hidden);
  const moreWidth = moreVisible ? morePanel.offsetWidth : 0;
  const moreHeight = moreVisible ? morePanel.offsetHeight : 0;
  const colorPanel = bar.querySelector('[data-floating-color-panel]');
  const colorVisible = Boolean(colorPanel && !colorPanel.hidden);
  const colorHeight = colorVisible ? colorPanel.offsetHeight : 0;
  let menuPlacement = null;
  if (moreVisible) {
    const horizontalChoices = [
      ['right', best.right - moreWidth],
      ['left', best.left]
    ];
    const verticalChoices = [
      ['below', best.bottom + 10],
      ['above', best.top - moreHeight - 10]
    ];
    const menuCandidates = [];
    for (const [horizontal, left] of horizontalChoices) {
      for (const [vertical, top] of verticalChoices) {
        const menuRect = candidateRect(left, top, moreWidth, moreHeight, `${vertical}-${horizontal}`);
        const overflow =
          Math.max(0, safe.left - menuRect.left) +
          Math.max(0, menuRect.right - safe.right) +
          Math.max(0, safe.top - menuRect.top) +
          Math.max(0, menuRect.bottom - safe.bottom);
        const collision = blockers.reduce((total, blocker) => total + rectOverlapArea(menuRect, blocker, 6), 0);
        const selectedOverlap = rectOverlapArea(menuRect, itemRect, 8);
        menuCandidates.push({ horizontal, vertical, score: overflow * 10000 + collision + selectedOverlap * 5 });
      }
    }
    menuCandidates.sort((a, b) => a.score - b.score);
    menuPlacement = menuCandidates[0] || null;
  }

  const nextX = Math.round(best.left);
  const nextY = Math.round(best.top);
  const previousX = Number(bar.dataset.positionX);
  const previousY = Number(bar.dataset.positionY);
  const targetChanged = nextX !== previousX || nextY !== previousY;
  const shouldAnimateReanchor =
    source !== 'manual' &&
    Number.isFinite(previousX) &&
    Number.isFinite(previousY) &&
    Math.hypot(nextX - previousX, nextY - previousY) > 24 &&
    !window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;

  if (targetChanged) {
    floatingToolbarMoveAnimation?.cancel?.();
    floatingToolbarMoveAnimation = null;
    bar.style.setProperty('--floating-toolbar-x', `${nextX}px`);
    bar.style.setProperty('--floating-toolbar-y', `${nextY}px`);
  }
  bar.dataset.positionX = String(nextX);
  bar.dataset.positionY = String(nextY);
  bar.dataset.placement = best.key;
  bar.dataset.anchorSource = source;
  if (manualPosition) {
    manualPosition.x = nextX;
    manualPosition.y = nextY;
  }
  bar.classList.toggle('is-snapped', source === 'border');
  bar.classList.toggle('is-magnet-snapped', Boolean(manualPosition?.snapped));
  bar.classList.toggle('more-above', menuPlacement?.vertical === 'above');
  bar.classList.toggle('more-align-left', menuPlacement?.horizontal === 'left');
  bar.classList.toggle(
    'color-above',
    colorVisible && best.bottom + colorHeight + 10 > safe.bottom && best.top - colorHeight - 10 >= safe.top
  );

  // Small caret steps track immediately. Larger jumps interpolate from the
  // toolbar's current visual position, so consecutive clicks cannot rewind it.
  if (shouldAnimateReanchor) {
    const animation = bar.animate(
      [
        { transform: `translate3d(${barRect.left}px, ${barRect.top}px, 0) scale(var(--floating-toolbar-scale, 1))` },
        { transform: `translate3d(${nextX}px, ${nextY}px, 0) scale(var(--floating-toolbar-scale, 1))` }
      ],
      { duration: 180, easing: 'cubic-bezier(.2,.82,.2,1)' }
    );
    floatingToolbarMoveAnimation = animation;
    animation.finished
      .then(() => {
        if (floatingToolbarMoveAnimation !== animation) return;
        floatingToolbarMoveAnimation = null;
        animation.cancel();
      })
      .catch(() => {});
  }

  if (moreVisible && morePanel.querySelector('.floating-menu-subpanel:not([hidden])')) {
    requestAnimationFrame(positionFloatingSubmenu);
  }
}
